// Generator of test/complement_ref_1_11.inc, the stored E-value vector of
// complement_test (e). It is built against FASTag 1.11.0 (78390cd), NOT
// against the tree it tests: drop this file and complement_synth.h into a
// 78390cd checkout, add
//   add_executable(complement_ref_gen test/complement_ref_gen.cpp)
//   target_link_libraries(complement_ref_gen PRIVATE fastag_core)
// to its CMakeLists.txt (Release, as the CI builds it) and run
//   complement_ref_gen > complement_ref_1_11.inc
// It uses only Param fields 1.11 has, and spells out the 1.11 tool's
// defaults (78390cd FASTag.cpp:1015-1028) by hand, since 1.11 has no
// cliDefaultParam().
//
