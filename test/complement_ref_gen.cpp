#include "FASTagger.h"
#include "complement_synth.h"

#include <OpenMS/CHEMISTRY/ModificationsDB.h>
#include <OpenMS/CHEMISTRY/ResidueModification.h>

#include <cstdio>

int main()
{
  FASTag::Param cli;
  cli.tag_length = 3;
  cli.max_extension = 0;
  cli.max_gaps = 1;
  cli.deisotope = true;
  cli.peaks_per_window = 10;
  cli.frag_tol = 20.0;
  cli.tol_ppm = true;
  cli.max_peak_count = 400;
  cli.max_tag_count = 50;
  cli.max_evalue = 20.0;
  cli.gap_penalty = 100.0;
  {
    const OpenMS::ResidueModification* mod =
        OpenMS::ModificationsDB::getInstance()->getModification("Carbamidomethyl (C)");
    FASTag::ModSpec ms;
    ms.residue = mod->getOrigin() == 'I' ? 'L' : mod->getOrigin();
    ms.delta = mod->getDiffMonoMass();
    ms.name = mod->getId();
    ms.variable = false;
    cli.mods.push_back(ms);
  }
  FASTag::Param nodeiso = cli;
  nodeiso.deisotope = false;
  const FASTag::Param* params[2] = {&cli, &nodeiso};

  std::printf("// Generated by test/complement_ref_gen.cpp against FASTag 1.11.0 (78390cd).\n");
  std::printf("// {case, param (0 = CLI defaults, 1 = deisotope off), rank, seq, charge, evalue, p_complement}\n");
  for (int pi = 0; pi < 2; ++pi)
  {
    const FASTag::Tables tab(*params[pi]);
    for (int ci = 0; ci < 5; ++ci)
    {
      const ComplementSynth::Case& c = ComplementSynth::kRefCases[ci];
      const ComplementSynth::Spec s =
          ComplementSynth::make(c.pep, c.charge, c.y2, c.iso, 0.0, c.noise, c.seed);
      const auto tags = FASTag::tagSpectrum(s.spec, s.prec_mz, c.charge, *params[pi], tab);
      for (size_t r = 0; r < tags.size() && r < 10; ++r)
        std::printf("{%d, %d, %zu, \"%s\", %d, %.17g, %.17g},\n", ci, pi, r, tags[r].seq.c_str(),
                    tags[r].charge, tags[r].evalue, tags[r].p_complement);
      std::printf("{%d, %d, 999, \"\", 0, %zu, 0},  // tag count\n", ci, pi, tags.size());
    }
  }
  return 0;
}
