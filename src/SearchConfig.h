// Search-engine configuration from a FASTag run (FASTag 1.12, items #5/#17).
//
// A SearchPlan holds what FASTag knows about the run that a database search
// needs: the database (the reduced FASTA, or the input one), the fixed and
// variable modifications FASTag was given, tolerances, missed cleavages and
// the decoy convention. renderSage writes a complete Sage configuration;
// renderComet writes the Comet keys FASTag manages, and mergeKeyValueTemplate
// puts them into a `comet -p` parameter file.
//
// Engine conventions are copied from OpenMS's adapters (TOPP sources cannot
// be linked from a tool) and cited where used:
//   - Sage term symbols '^' '$' '[' ']' from SageAdapter::getModDetails;
//   - Comet's fragment bin policy (CometAdapter.cpp, "ion trap ms/ms: 1.0005
//     tolerance, 0.4 offset ... high res ms/ms: 0.02 tolerance, 0.0 offset"),
//     the reset of unused variable_modNN slots to "0.0 X 0 3 -1 0 0 0.0", the
//     explicit add_C_cysteine = 0 (Comet applies Carbamidomethyl by default),
//     the variable-mod terminus encoding (CometModification.cpp) and the rule
//     that [COMET_ENZYME_INFO] must come last.
// The enzyme is always trypsin: placement windows are tryptic (ProteomeIndex).
//
// Copyright (c) 2026 Oliver Kohlbacher and contributors
// SPDX-License-Identifier: MIT
#pragma once

#include "Digest.h"

#include <cstddef>
#include <cstdint>
#include <map>
#include <string>
#include <utility>
#include <vector>

namespace OpenMS
{
  class ResidueModification;
}

namespace FASTag::SearchConfig
{
  struct SearchPlan
  {
    std::string database;  ///< FASTA the engine searches
    std::string spectra;   ///< the run (Sage mzml_paths; a comment for Comet)
    std::vector<const OpenMS::ResidueModification*> fixed, variable;
    std::vector<double> mass_offsets;  ///< Comet mass offsets besides 0 (#17)
    int isotope_errors = 0;            ///< 0..n precursor isotope errors; 0 = none
    int missed_cleavages = 1;
    double fragment_tolerance = 20.0;
    bool fragment_ppm = true;
    double precursor_tolerance = 10.0;
    bool precursor_ppm = true;
    std::string decoy_prefix;          ///< "" = the engine's FASTag default (rev_ / DECOY_)
    std::string fastag_version;        ///< written into the header comment
  };

  /// The decoy prefix a plan uses for @p engine ("sage" or "comet").
  std::string decoyPrefix(const SearchPlan& p, const std::string& engine);

  /// Sage term symbol and residue for one modification, as SageAdapter
  /// writes them: "^" peptide N-term, "$" peptide C-term, "[" protein N-term,
  /// "]" protein C-term, then the residue letter unless it is any (X).
  std::string sageModKey(const OpenMS::ResidueModification& mod);

  /// A complete Sage configuration (JSON): trypsin (KR, not before P),
  /// FASTag's missed cleavages, the plan's mods (static mods on one key are
  /// summed; variable ones listed), tolerances, isotope errors, decoys
  /// generated by Sage over the database with the plan's prefix.
  std::string renderSage(const SearchPlan& p);

  struct CometBins
  {
    double tol = 1.0005, offset = 0.4;
    int theoretical = 1;
  };
  /// CometAdapter's bin policy: a high-resolution fragment tolerance (ppm, or
  /// at most 0.1 Da) gives bin width 2 x the tolerance in Da at m/z 1000,
  /// floored at 0.01, offset 0.0 and theoretical_fragment_ions 0; a coarser
  /// one gives Comet's ion-trap defaults 1.0005 / 0.4 / 1.
  CometBins cometFragmentBins(double tolerance, bool ppm);

  /// Every Comet key FASTag manages, in the order renderComet writes them:
  /// database and decoys, precursor tolerance and isotope error, enzyme and
  /// missed cleavages, all variable_mod01..15 slots (unused ones reset), the
  /// fragment bins, mass_offsets, and every add_* key (0.0 unless the plan
  /// sets it), so no chemistry of a template survives.
  /// Returns "" or an error (a modification Comet cannot express).
  std::string cometKeys(const SearchPlan& p, std::vector<std::pair<std::string, std::string>>& keys);

  /// The managed Comet keys as a parameter fragment, with a header that says
  /// to merge it into `comet -p` defaults (-search_config_template).
  std::string renderComet(const SearchPlan& p, std::string* err = nullptr);

  struct MergeResult
  {
    std::string text;
    std::string error;                  ///< "" on success
    std::vector<std::string> warnings;  ///< e.g. a rewritten enzyme number
  };

  /// True if @p key belongs to a family FASTag manages as a whole: every
  /// variable_modNN (two digits) and every add_* key.
  bool cometManagedFamily(const std::string& key);

  /// Merges @p keys into a Comet parameter file @p tmpl: a line whose key is
  /// in @p keys gets its value (an inline comment is kept), a line of a
  /// managed family whose key is not in @p keys is dropped, keys the template
  /// lacks are inserted before [COMET_ENZYME_INFO]; comments, blank lines,
  /// the version header and unmanaged keys stay as they are. The template's
  /// enzyme table must hold trypsin (cut KR, not before P, C-terminal): the
  /// search_enzyme_number and sample_enzyme_number keys are set to its
  /// number, and a different number in the template is a warning. No table,
  /// or no trypsin in it, is an error.
  MergeResult mergeKeyValueTemplate(const std::string& tmpl,
                                    const std::vector<std::pair<std::string, std::string>>& keys);

  // ---- #17: mass shifts as search-engine configuration --------------------
  //
  // The gap peaks of one FD::GapResult (the one -massgap_out reports) become
  // variable modifications, Comet mass offsets or, for an unalkylated-looking
  // run, a suggested fixed Cys alkylation in the plan. A candidate list for an
  // FDR-controlling engine, not an identification.
  //
  // Reference frame: a gap is relative to the peptide with the plan's fixed
  // modifications applied; on the labelled side it contains a fixed terminal
  // label. Rules, per peak in descending spectra order (ties: |delta|
  // ascending, then delta):
  //   0. isotope: within the window of n x 1.00335 (n = 1..3) and closer to it
  //      than to every single modification -> skipped_isotope; the largest n
  //      raises the plan's isotope errors;
  //   1. a fixed terminal label L: a peak at L -> expected_label, at -L ->
  //      label_incomplete (WARN); a peak explained as L + X goes on as X;
  //   2. a fixed residue modification F: at +F -> the same Unimod name on K, H
  //      or the peptide N-term (those ModificationsDB knows, the fixed residue
  //      left out); at -F -> fixed_mod_questionable (WARN);
  //   3. one modification -> variable (a SILAC label only when the SILAC call
  //      is not none, else skipped_silac; a Cys alkylation without a fixed Cys
  //      modification and with >= half the C-containing placements -> fixed,
  //      WARN); already in the plan -> already_searched;
  //   4. a combination, no explanation, or a substitution share > 0.5 ->
  //      Comet offset at the 4-decimal gap (Sage, or a negative offset:
  //      dropped_engine);
  //   5. caps: max_variable peaks as variable modifications, max_offsets
  //      offsets (0 is always first and not counted), 15 Comet slots with the
  //      plan's own: the rest dropped_cap;
  //   -search_shifts variable or offsets: what the mode does not export is
  //      dropped_mode (offsets: rules 2 and 3 export the gap as an offset).
  // Site expansion (expand_sites): a variable modification of rule 3 gains a
  // residue with >= site_min_count counted samples and >= site_min_share of the
  // peak's counted samples that ModificationsDB knows the name on.

  /// The evidence of one histogram row (absorbed neighbour bins included).
  struct RowEvidence
  {
    std::uint64_t spectra = 0;       ///< samples in the row
    std::uint64_t substitution = 0;  ///< ... interpreted as a substitution (sub:X->Y)
    std::uint64_t localized = 0;     ///< ... with a localized site
    std::uint64_t site_counted = 0;  ///< ... that count for site expansion (siteSampleCounts)
    std::map<char, std::uint64_t> sites;  ///< residue -> counted samples
    void add(const RowEvidence& o);
  };
  using PeakEvidence = RowEvidence;

  /// A localized sample counts for site expansion when its site is unique
  /// (ties == 1), explained by at least @p min_ions ions and its region spans
  /// more than one residue.
  bool siteSampleCounts(char residue, int score, int ties, int region_len, int min_ions);

  /// The evidence of @p peak: the sum over its member rows (indices into @p rows).
  PeakEvidence peakEvidence(const FASTag::Digest::GapPeak& peak, const std::vector<RowEvidence>& rows);

  enum class ShiftMode { None, Variable, Offsets, Both };
  /// none, variable, offsets, both; false for anything else.
  bool parseShiftMode(const std::string& s, ShiftMode& m);

  struct ShiftSettings
  {
    ShiftMode mode = ShiftMode::None;
    std::string engine = "sage";       ///< sage or comet
    double tol = 0.02;                 ///< the gap window in Da (FD::GapSettings::window)
    std::size_t max_variable = 3, max_offsets = 10;
    bool expand_sites = false;
    double site_min_share = 0.2;
    std::uint64_t site_min_count = 10;
    std::uint64_t c_placements = 0;    ///< delta samples whose peptide holds a C
  };

  struct ShiftDecision
  {
    std::size_t peak = 0;              ///< 1-based, as -massgap_out numbers the peaks
    double delta = 0.0;
    std::uint64_t spectra = 0;
    std::string explanation;           ///< "A + B", or "none"
    std::string action;
    std::string mod_id;                ///< the exported modification(s), ';'-joined; "-" for none
    std::string sites;                 ///< residues / terms of mod_id, ','-joined; "-" for none
    double exported = 0.0;             ///< mass of the modification or the offset; NaN for none
    double substitution_share = 0.0;
    std::uint64_t localized = 0;
    std::string reason;
  };

  struct ShiftOutcome
  {
    std::vector<ShiftDecision> decisions;  ///< one per peak, in GapResult order
    std::vector<std::string> warnings, info;
    int isotope_max = 0;                   ///< largest isotope multiple skipped
    std::size_t variable = 0, offsets = 0, fixed = 0;  ///< exported entries
  };

  /// Applies the rules above to @p gaps (with @p evidence aligned to its
  /// peaks; missing entries count as no evidence), adding to @p plan's
  /// variable and fixed modifications, mass offsets and isotope errors.
  /// @p mods and @p combos are the ones the gap result was explained with.
  ShiftOutcome shiftsToPlan(const FASTag::Digest::GapResult& gaps, const std::vector<PeakEvidence>& evidence,
                            const std::vector<FASTag::Digest::GapMod>& mods,
                            const std::vector<FASTag::Digest::Combo>& combos, const ShiftSettings& s,
                            SearchPlan& plan);

  /// The -search_shifts_out TSV: '# ' header lines, then one row per decision.
  bool writeShiftDecisions(const std::string& path, const std::vector<std::string>& header,
                           const std::vector<ShiftDecision>& decisions, std::string* err);
}
