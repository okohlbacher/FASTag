#!/bin/bash
# Batch 2: DirecTag's complement charge rule (FASTAG_DIAG_COMPL_CHARGE=1), second diagnostic build.
cd /scratch/kohlbach/longtag
export FASTAG_BIN=/scratch/kohlbach/longtag/build2/FASTag
R=./run_diag.sh
for DS in PXD076528 PXD001819 PXD003531 PXD000001; do
  $R b2_base $DS
  FASTAG_DIAG_COMPL_CHARGE=1 $R zc $DS
  FASTAG_DIAG_COMPL_CHARGE=1 FASTAG_DIAG_CPAIR=3 $R zc_cpair3 $DS
  FASTAG_DIAG_COMPL_CHARGE=1 FASTAG_DIAG_PVALS=1 $R zc_pvals $DS
done
for DS in PXD001819; do
  FASTAG_DIAG_COMPL_CHARGE=1 FASTAG_DIAG_COMPLEMENT_TOL=0.5 $R zc_ctol05 $DS
  FASTAG_DIAG_COMPL_CHARGE=1 FASTAG_DIAG_COMPLEMENT_TOL=0.5 FASTAG_DIAG_CPAIR=3 $R zc_ctol05_cpair3 $DS
  FASTAG_DIAG_COMPL_CHARGE=1 FASTAG_DIAG_COMPLEMENT_TOL=0.5 FASTAG_DIAG_CPAIR=1 $R zc_ctol05_cpair1 $DS
  FASTAG_DIAG_COMPL_CHARGE=1 FASTAG_DIAG_COMPLEMENT_TOL=0.5 FASTAG_DIAG_PVALS=1 $R zc_ctol05_pvals $DS
done
for DS in PXD076528; do
  FASTAG_DIAG_COMPL_CHARGE=1 FASTAG_DIAG_CPAIR=1 $R zc_cpair1 $DS
  FASTAG_DIAG_COMPL_CHARGE=1 FASTAG_DIAG_CPAIR=2 $R zc_cpair2 $DS
done
echo BATCH2_DONE
