#!/bin/bash
# Batch 1 of the tag-length-3 analysis: hypothesis reruns (diagnostic FASTag 1.9.0 build, matched settings).
cd /scratch/kohlbach/longtag
R=./run_diag.sh
for DS in PXD001819 PXD076528 PXD003531 PXD000001; do
  FASTAG_DIAG_PVALS=1 $R pvals $DS
  FASTAG_DIAG_CPAIR=1 $R cpair1 $DS
  FASTAG_DIAG_CPAIR=2 $R cpair2 $DS
  FASTAG_DIAG_CPAIR=3 $R cpair3 $DS
  FASTAG_DIAG_CPAIR=3 FASTAG_DIAG_PVALS=1 $R cpair3_pvals $DS
  DEISO=" " $R deiso $DS
  MAXP=50 $R maxp50 $DS
  MAXP=150 $R maxp150 $DS
  MAXP=200 $R maxp200 $DS
  PPW=10 $R ppw10 $DS
done
for DS in PXD001819; do
  FASTAG_DIAG_COMPLEMENT_TOL=0.5 $R ctol05 $DS
  FASTAG_DIAG_COMPLEMENT_TOL=0.25 $R ctol025 $DS
  FASTAG_DIAG_COMPLEMENT_TOL=0.1 $R ctol01 $DS
  FASTAG_DIAG_COMPLEMENT_TOL=0.5 FASTAG_DIAG_CPAIR=1 $R ctol05_cpair1 $DS
  FASTAG_DIAG_COMPLEMENT_TOL=0.5 FASTAG_DIAG_CPAIR=2 $R ctol05_cpair2 $DS
  FASTAG_DIAG_COMPLEMENT_TOL=0.5 FASTAG_DIAG_CPAIR=3 $R ctol05_cpair3 $DS
  FASTAG_DIAG_COMPLEMENT_TOL=0.5 FASTAG_DIAG_CPAIR=3 FASTAG_DIAG_PVALS=1 $R ctol05_cpair3_pvals $DS
  FASTAG_DIAG_COMPLEMENT_TOL=0.5 FASTAG_DIAG_PVALS=1 $R ctol05_pvals $DS
  FTOL=0.4 $R ftol04 $DS
  FTOL=0.6 $R ftol06 $DS
done
for DS in PXD076528; do
  FTOL=0.01 $R ftol001 $DS
  FTOL=0.03 $R ftol003 $DS
  FASTAG_DIAG_COMPLEMENT_TOL=0.01 $R ctol001 $DS
  FASTAG_DIAG_COMPLEMENT_TOL=0.005 $R ctol0005 $DS
done
echo BATCH1_DONE
