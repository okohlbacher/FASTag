#!/usr/bin/env python3
"""Regenerate the 'Table and figure index' section of README.md: every file in results/ with its FASTag
version, the figures that read it and its first provenance line, and every figure in figures/ with the script
and tables behind it. The section sits between the two marker comments and is replaced in place.

    python3 scripts/readme_inventory.py            # rewrite README.md
    python3 scripts/readme_inventory.py --check    # exit 1 if README.md is out of date
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
START, END = "<!-- inventory:start -->", "<!-- inventory:end -->"
SUFFIX = re.compile(r"_(v1[0-9]0)$")
ARGS = re.compile(r'^a = args\("([^"]+)"(, versioned=True)?\)', re.M)
RELEASE = {"v180": "1.8.0", "v190": "1.9.0", "v170": "1.7.0", "v161": "1.6.1"}


def base_of(name: str) -> tuple[str, str]:
    stem = name.rsplit(".", 1)[0] if "." in name else name
    m = SUFFIX.search(stem)
    return (stem[: m.start()], m.group(1)) if m else (stem, "")


def provenance(p: Path) -> str:
    if p.is_dir():
        n = sum(1 for _ in p.rglob("*") if _.is_file())
        return f"directory, {n} files"
    if p.suffix not in (".tsv", ".json"):
        return ""
    with p.open(errors="replace") as fh:
        for line in fh:
            if line.startswith("#"):
                s = line.lstrip("# ").strip()
                return (s[:157] + "...") if len(s) > 160 else s
            break
    return "(no provenance header)" if p.suffix == ".tsv" else "JSON record"


def version(name: str, prov: str) -> str:
    vs = re.findall(r"v1[0-9]{2}", name)
    if "_vs_" in name and len(vs) == 2:
        return " vs ".join(RELEASE.get(x, x) for x in vs)
    if "_rc_vs_" in name:
        return "1.8.0 RC vs 1.8.0"
    _, v = base_of(name)
    if v:
        return RELEASE.get(v, v)
    for pat, lab in ((r"1\.2\.x|pre-port|pre-1\.4|v0\.13", "pre-port"), (r"FASTag 1\.10\.0", "1.10.0"),
                     (r"RC 71a68e0", "1.8.0 RC"),
                     (r"1\.6\.1", "1.6.1/1.8.0"), (r"1\.8\.0", "1.8.0")):
        if re.search(pat, prov):
            return lab
    return "1.8.0" if not re.search(r"\d\.\d\.\d", prov) else "see source"


def scripts() -> dict[str, tuple[str, bool, str]]:
    out = {}
    for s in sorted((ROOT / "scripts").glob("fig_*.py")):
        src = s.read_text()
        m = ARGS.search(src)
        if m:
            out[s.name] = (m.group(1), bool(m.group(2)), src)
    return out


TRACER = """
import runpy, sys
res = sys.argv[1]
seen = set()
def hook(ev, args):
    if ev == "open" and isinstance(args[0], str) and args[0].startswith(res):
        seen.add(args[0][len(res):].lstrip("/").split("/")[0])
sys.addaudithook(hook)
script = sys.argv[2]
sys.argv = [script] + sys.argv[3:]
try:
    runpy.run_path(script, run_name="__main__")
finally:
    sys.stderr.write("\\nREAD " + "\\t".join(sorted(seen)) + "\\n")
"""


def traced_reads(sc, variants, res) -> dict[str, list[str]]:
    """Run every figure script (and its release variants) with an audit hook and record the results/ files it opens."""
    import subprocess
    import tempfile
    rdir = str((ROOT / "results").resolve())
    readers: dict[str, list[str]] = {}
    with tempfile.TemporaryDirectory() as tmp:
        for script, (fig, _, _) in sc.items():
            for v in [""] + variants.get(script[:-3], []):
                cmd = [sys.executable, "-c", TRACER, rdir, str(ROOT / "scripts" / script),
                       "--results", rdir, "--out", tmp]
                if script[:-3] in variants:  # explicit, also '': a versioned script defaults to v190
                    cmd += ["--suffix", v]
                p = subprocess.run(cmd, capture_output=True, text=True)
                line = [l for l in p.stderr.splitlines() if l.startswith("READ ")]
                for name in (line[-1][5:].split("\t") if line else []):
                    if name:
                        readers.setdefault(name, []).append(fig + (f"_{v}" if v else ""))
    return readers


def esc(s: str) -> str:
    return s.replace("|", "\\|")


def build() -> str:
    from importlib.util import module_from_spec, spec_from_file_location
    spec = spec_from_file_location("figs", ROOT / "src" / "fastag_bench" / "figures.py")
    mod = module_from_spec(spec)
    spec.loader.exec_module(mod)
    variants = mod.VARIANTS
    sc = scripts()
    res = sorted(p for p in (ROOT / "results").iterdir() if not p.name.startswith("."))
    readers = traced_reads(sc, variants, res)
    lines = [START, "", "## Table and figure index", "",
             "Generated by `python3 scripts/readme_inventory.py` (do not edit by hand). Version: the FASTag release the "
             "table describes (`pre-port` = before 1.7.0, not valid for 1.8.0 speed). Source: the first `#` line of the "
             "file; the full provenance and conditions are in the file header.", "",
             "### Result tables (`results/`)", "", "| file | FASTag | figure | source |", "|---|---|---|---|"]
    for p in res:
        prov = provenance(p)
        name = p.name + ("/" if p.is_dir() else "")
        figs = ", ".join(sorted(set(readers.get(p.name, [])))) or "table only"
        lines.append(f"| `{name}` | {version(p.name, prov)} | {figs} | {esc(prov)} |")
    lines += ["", "### Figures (`figures/`, PDF and PNG; `fastag-bench figures` renders all of them)", "",
              "| figure | script | tables |", "|---|---|---|"]
    figs = sorted({p.stem for p in (ROOT / "figures").glob("*.pdf")})
    for f in figs:
        b, v = base_of(f)
        script = next((s for s, (n, _, _) in sc.items() if n == b), None)
        tabs = sorted(n for n, fl in readers.items() if f in fl)
        sfx = f" `--suffix {v}`" if v else (" `--suffix ''`" if script and script[:-3] in variants else "")
        call = f"`scripts/{script}`" + sfx if script else "(no script)"
        lines.append(f"| `{f}` | {call} | {', '.join(f'`{t}`' for t in tabs) or '-'} |")
    lines += ["", END]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    readme = ROOT / "README.md"
    text = readme.read_text()
    block = build()
    if START in text:
        new = text[: text.index(START)] + block + text[text.index(END) + len(END):]
    else:
        new = text.replace("\n## License", "\n" + block + "\n\n## License")
    if a.check:
        return 0 if new == text else 1
    readme.write_text(new)
    print(f"{readme}: index of {block.count(chr(10))} lines")
    return 0


if __name__ == "__main__":
    sys.exit(main())
