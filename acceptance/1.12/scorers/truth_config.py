#!/usr/bin/env python3
"""Sage 0.14.7 truth-search configurations of the held-out runs of #2, #6 and #9 (PREREG-item02/06/09.md), one
JSON per row of a truth table (scorers/truth/item02.tsv, item09.tsv). Fixed before any held-out run.

The JSON is the closed ground-truth search of the paper harness (bench/fastag-bench sage.py, mode 'closed': bucket
32768, missed cleavages 2, length 7-50, fragment m/z 150-2000, peptide mass 500-5000, b/y ions, min ion index 2,
decoys rev_ generated by Sage, isotope errors [0, 1], min 15 / max 150 peaks, one PSM per spectrum), with the
table's database, enzyme, static and variable modifications, max_variable_mods, precursor and fragment tolerance and
deisotope. mode 'charge_truth' (#6) is that search with precursor_charge [1, 4] and isotope_errors [-1, 3]
(sage.py mode charge_truth). FDR: target rank-1 PSMs with spectrum_q <= 0.01 (acclib.sage_truth).
Columns: manifest, pxd, run_dir, search_input (path below the staged root), organism, fasta, fasta_sha256, enzyme
(Trypsin | Trypsin/P), static_mods (JSON), variable_mods (JSON), max_variable_mods, precursor_ppm, fragment
('<v> ppm' | '<v> Da'), deisotope (true|false), evaluable (yes | no: reason), note.
Usage: truth_config.py <truth table> <staged root> <fasta root> <out dir> [--mode closed|charge_truth]
       writes <out>/<manifest>/<run_dir>/sage.json (mzml_paths: <staged root>/<search_input>; for charge_truth the
       charge-stripped copy <out>/<manifest>/<run_dir>/input.nocharge.mzML, made by strip_charge.py)"""
import argparse
import csv
import json
from pathlib import Path


def config(r, staged, fasta_root, mode, out_dir):
    v, u = r["fragment"].split()
    enz = {"missed_cleavages": 2, "min_len": 7, "max_len": 50, "cleave_at": "KR"}
    if r["enzyme"] == "Trypsin":
        enz["restrict"] = "P"
    mz = (str(Path(out_dir) / "input.nocharge.mzML") if mode == "charge_truth"
          else str(Path(staged) / r["search_input"]))
    cfg = {
        "database": {"bucket_size": 32768, "enzyme": enz, "fragment_min_mz": 150.0, "fragment_max_mz": 2000.0,
                     "peptide_min_mass": 500.0, "peptide_max_mass": 5000.0, "ion_kinds": ["b", "y"],
                     "min_ion_index": 2, "static_mods": json.loads(r["static_mods"]),
                     "variable_mods": json.loads(r["variable_mods"]), "max_variable_mods": int(r["max_variable_mods"]),
                     "decoy_tag": "rev_", "generate_decoys": True, "fasta": str(Path(fasta_root) / r["fasta"])},
        "precursor_tol": {"ppm": [-float(r["precursor_ppm"]), float(r["precursor_ppm"])]},
        "fragment_tol": {("da" if u.lower() == "da" else "ppm"): [-float(v), float(v)]},
        "isotope_errors": [0, 1], "deisotope": r["deisotope"] == "true", "chimera": False, "wide_window": False,
        "predict_rt": True, "min_peaks": 15, "max_peaks": 150, "report_psms": 1, "mzml_paths": [mz],
    }
    if mode == "charge_truth":
        cfg["precursor_charge"] = [1, 4]
        cfg["isotope_errors"] = [-1, 3]
    return cfg


def main():
    ap = argparse.ArgumentParser()
    for a in ("table", "staged", "fasta_root", "out"):
        ap.add_argument(a)
    ap.add_argument("--mode", default="closed", choices=["closed", "charge_truth"])
    ap.add_argument("--manifest")
    a = ap.parse_args()
    with open(a.table) as f:
        rows = list(csv.DictReader((l for l in f if not l.startswith("# ")), delimiter="\t"))
    n = 0
    for r in rows:
        if a.manifest and r["manifest"] != a.manifest:
            continue
        if not r["evaluable"].startswith("yes"):
            print("not evaluable:", r["manifest"], r["run_dir"], r["evaluable"])
            continue
        d = Path(a.out) / r["manifest"] / r["run_dir"]
        d.mkdir(parents=True, exist_ok=True)
        (d / "sage.json").write_text(json.dumps(config(r, a.staged, a.fasta_root, a.mode, d), indent=2) + "\n")
        n += 1
    print(f"{n} configurations written under {a.out}")


if __name__ == "__main__":
    main()
